 * ---------------------------------------------------
 * 
 * Encapsulation
 * Ibarat sebuah kantong yang menyimpan sesuatu dalam pemograman
 * Berfungsi
 * Mengumpulkan data dan tidak dapat diakses langsung dari luar
 * pada kasus "Ucup Guerero" kita tidak bisa mengubah
